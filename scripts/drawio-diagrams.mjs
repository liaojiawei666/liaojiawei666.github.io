import { createHash } from 'node:crypto';
import { spawn } from 'node:child_process';
import {
  access,
  copyFile,
  mkdir,
  readFile,
  readdir,
  rm,
  stat,
  writeFile,
} from 'node:fs/promises';
import { constants } from 'node:fs';
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourceRoot = join(projectRoot, 'src', 'diagrams');
const outputRoot = join(projectRoot, 'public', 'diagrams');
const manifestPath = join(outputRoot, '.drawio-manifest.json');
// draw.io Desktop 是 Electron 应用，每次导出都会在 user-data 与 cache 目录里
// 写入大量文件。该目录若位于 dev server 的监听范围内，Windows 的
// ReadDirectoryChangesW 会因缓冲区溢出而失效，导致文件监听永久停止工作。
// node_modules 默认被 Vite 的 watcher 忽略，因此放在这里。
const drawioRuntimeRoot = join(projectRoot, 'node_modules', '.cache', 'drawio');
const drawioUserDataRoot = join(drawioRuntimeRoot, 'user-data');
const drawioCacheRoot = join(drawioRuntimeRoot, 'cache');
const isCodexSandbox = Boolean(process.env.CODEX_PERMISSION_PROFILE);

const defaultManifest = {
  version: 1,
  diagrams: {},
};

async function exists(path) {
  try {
    await access(path, constants.F_OK);
    return true;
  } catch {
    return false;
  }
}

async function listDrawioFiles(directory) {
  if (!(await exists(directory))) return [];

  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await listDrawioFiles(path)));
    } else if (entry.isFile() && entry.name.endsWith('.drawio')) {
      files.push(path);
    }
  }

  return files.sort();
}

async function loadManifest() {
  if (!(await exists(manifestPath))) return structuredClone(defaultManifest);

  try {
    const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
    if (manifest?.version === 1 && manifest.diagrams) return manifest;
  } catch {
    // A malformed manifest will be regenerated by the next successful sync.
  }

  return structuredClone(defaultManifest);
}

async function saveManifest(manifest) {
  await mkdir(outputRoot, { recursive: true });
  const content = `${JSON.stringify(manifest, null, 2)}\n`;
  const current = (await exists(manifestPath))
    ? await readFile(manifestPath, 'utf8')
    : '';

  if (content !== current) {
    await writeFile(manifestPath, content, 'utf8');
  }
}

function sourceKey(sourcePath) {
  const key = relative(sourceRoot, resolve(sourcePath)).split(sep).join('/');
  if (!key || key.startsWith('../') || isAbsolute(key)) {
    throw new Error(`图表文件不在 src/diagrams 中：${sourcePath}`);
  }
  return key;
}

function outputPathForKey(key) {
  const outputPath = resolve(outputRoot, `${key}.svg`);
  const allowedPrefix = `${resolve(outputRoot)}${sep}`;
  if (!outputPath.startsWith(allowedPrefix)) {
    throw new Error(`图表输出路径越界：${outputPath}`);
  }
  return outputPath;
}

async function sourceHash(sourcePath) {
  return createHash('sha256')
    .update(await readFile(sourcePath))
    .digest('hex');
}

async function findDrawioBinary() {
  const configured = process.env.DRAWIO_BIN;
  const candidates = [
    configured,
    process.platform === 'win32'
      ? 'C:\\Program Files\\draw.io\\draw.io.exe'
      : undefined,
    process.platform === 'win32' && process.env.LOCALAPPDATA
      ? join(process.env.LOCALAPPDATA, 'Programs', 'draw.io', 'draw.io.exe')
      : undefined,
    process.platform === 'darwin'
      ? '/Applications/draw.io.app/Contents/MacOS/draw.io'
      : undefined,
  ].filter(Boolean);

  for (const candidate of candidates) {
    if (await exists(candidate)) return candidate;
  }

  return process.platform === 'win32' ? 'draw.io.exe' : 'drawio';
}

function runDrawio(binary, sourcePath, temporaryOutput) {
  const args = [
    `--user-data-dir=${drawioUserDataRoot}`,
    `--disk-cache-dir=${drawioCacheRoot}`,
    '--export',
    '--format',
    'svg',
    '--embed-diagram',
    '--border',
    '10',
    '--output',
    temporaryOutput,
    sourcePath,
  ];

  if (process.platform === 'win32') {
    args.push('--disable-gpu');
    if (isCodexSandbox) {
      // Codex 的受限 Windows 会让 Electron GPU sandbox 无法加载依赖 DLL。
      // --disable-gpu 仍可能启动软件合成 GPU 子进程，因此还要单独关闭
      // Chromium 的 GPU sandbox。外层 Codex sandbox 仍然限制此进程。
      args.push('--disable-gpu-sandbox', '--no-sandbox');
    }
  }

  return new Promise((resolvePromise, rejectPromise) => {
    const child = spawn(binary, args, {
      cwd: projectRoot,
      windowsHide: true,
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    let stderr = '';

    child.stderr.on('data', (chunk) => {
      stderr += chunk;
    });
    child.once('error', (error) => {
      rejectPromise(
        new Error(
          `无法调用 draw.io Desktop。请安装 draw.io，或通过 DRAWIO_BIN 指定路径。\n${error.message}`,
        ),
      );
    });
    child.once('exit', (code) => {
      if (code === 0) {
        resolvePromise();
      } else {
        rejectPromise(
          new Error(
            `draw.io 导出失败（退出码 ${code ?? 'unknown'}）。${stderr.trim()}`,
          ),
        );
      }
    });
  });
}

async function waitForFile(path, timeoutMs = 15_000) {
  const startedAt = Date.now();
  while (Date.now() - startedAt < timeoutMs) {
    if (await exists(path)) {
      const fileStat = await stat(path);
      if (fileStat.size > 0) return;
    }
    await new Promise((resolvePromise) => setTimeout(resolvePromise, 100));
  }

  throw new Error(`draw.io 未在 ${timeoutMs / 1000} 秒内生成文件：${path}`);
}

export async function syncDiagram(sourcePath, options = {}) {
  const key = sourceKey(sourcePath);
  const outputPath = outputPathForKey(key);
  const hash = await sourceHash(sourcePath);
  const manifest = options.manifest ?? (await loadManifest());
  const recorded = manifest.diagrams[key];

  if (
    !options.force &&
    recorded?.sha256 === hash &&
    recorded?.output === `${key}.svg` &&
    (await exists(outputPath))
  ) {
    return { changed: false, key, outputPath, manifest };
  }

  await mkdir(dirname(outputPath), { recursive: true });
  await mkdir(drawioUserDataRoot, { recursive: true });
  await mkdir(drawioCacheRoot, { recursive: true });
  const temporaryOutput = `${outputPath}.tmp.svg`;
  await rm(temporaryOutput, { force: true });

  try {
    const binary = await findDrawioBinary();
    await runDrawio(binary, sourcePath, temporaryOutput);
    await waitForFile(temporaryOutput);

    const svgStart = (await readFile(temporaryOutput, 'utf8')).slice(0, 500);
    if (!svgStart.includes('<svg')) {
      throw new Error(`draw.io 生成的文件不是有效 SVG：${temporaryOutput}`);
    }

    await copyFile(temporaryOutput, outputPath);
  } finally {
    await rm(temporaryOutput, { force: true });
  }

  manifest.diagrams[key] = {
    sha256: hash,
    output: `${key}.svg`,
  };
  await saveManifest(manifest);

  return { changed: true, key, outputPath, manifest };
}

export async function removeDiagram(sourcePath, options = {}) {
  const key = sourceKey(sourcePath);
  const manifest = options.manifest ?? (await loadManifest());
  const recorded = manifest.diagrams[key];

  if (!recorded) return { changed: false, key, manifest };

  const outputPath = outputPathForKey(key);
  await rm(outputPath, { force: true });
  delete manifest.diagrams[key];
  await saveManifest(manifest);

  return { changed: true, key, manifest };
}

export async function syncAllDiagrams(options = {}) {
  await mkdir(sourceRoot, { recursive: true });
  await mkdir(outputRoot, { recursive: true });

  const manifest = await loadManifest();
  const sourceFiles = await listDrawioFiles(sourceRoot);
  const currentKeys = new Set(sourceFiles.map(sourceKey));
  let changed = 0;

  for (const sourcePath of sourceFiles) {
    const result = await syncDiagram(sourcePath, {
      force: options.force,
      manifest,
    });
    if (result.changed) changed += 1;
  }

  for (const key of Object.keys(manifest.diagrams)) {
    if (!currentKeys.has(key)) {
      const outputPath = outputPathForKey(key);
      await rm(outputPath, { force: true });
      delete manifest.diagrams[key];
      changed += 1;
    }
  }

  await saveManifest(manifest);
  return { changed, total: sourceFiles.length };
}

export default function drawioDiagrams() {
  const pending = new Map();

  function schedule(server, path, action) {
    if (!path.endsWith('.drawio')) return;
    if (!resolve(path).startsWith(`${resolve(sourceRoot)}${sep}`)) return;

    clearTimeout(pending.get(path));
    pending.set(
      path,
      setTimeout(async () => {
        pending.delete(path);
        try {
          const result =
            action === 'unlink'
              ? await removeDiagram(path)
              : await syncDiagram(path, { force: true });

          if (result.changed) {
            console.log(`[drawio] ${result.key} 已同步`);
            server.ws.send({ type: 'full-reload' });
          }
        } catch (error) {
          server.config.logger.error(`[drawio] ${error.message}`);
        }
      }, 250),
    );
  }

  return {
    name: 'drawio-diagrams',
    async buildStart() {
      const result = await syncAllDiagrams();
      if (result.changed > 0) {
        console.log(`[drawio] 已同步 ${result.changed} 个图表`);
      }
    },
    configureServer(server) {
      server.watcher.add(sourceRoot);
      server.watcher.on('add', (path) => schedule(server, path, 'sync'));
      server.watcher.on('change', (path) => schedule(server, path, 'sync'));
      server.watcher.on('unlink', (path) => schedule(server, path, 'unlink'));
    },
  };
}

const isCommandLine =
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href;

if (isCommandLine) {
  const force = process.argv.includes('--force');
  const result = await syncAllDiagrams({ force });
  console.log(`draw.io 图表同步完成：${result.changed}/${result.total} 个文件已更新`);
}
